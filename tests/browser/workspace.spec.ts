import { test, expect } from "@playwright/test";
import { loadSample, finalStep, submit, openSubmitted, seedAdmin, next } from "./flow-helpers";
import { assessmentFixture } from "../fixtures/assessment";

test("applicant submits, admin analyzes and confirms a separate decision, applicant sees status only", async ({ page, context }, testInfo) => {
  let requests = 0;
  await page.route("**/api/analyze", async (route) => {
    requests++;
    const payload = route.request().postDataJSON();
    expect(payload.consent).toBe(true);
    expect(payload.application.reference).toBe("ÖRNEK-002");
    expect(payload.application.notes).toBe("");
    expect(payload.application.narratives.fictionalExcerpts).toBe("");
    expect(JSON.stringify(payload)).not.toContain("YÖNETİCİYE ÖZEL");
    await route.fulfill({ json: { status: "success", result: assessmentFixture() } });
  });
  await page.goto("/"); await loadSample(page); await finalStep(page);
  await expect(page.locator('[name="analysis-mode"], [name="notes"], [name="narratives.fictionalExcerpts"]')).toHaveCount(0);
  await expect(page.locator("#review-report, #human-review")).toHaveCount(0);
  await submit(page); expect(requests).toBe(0);
  await page.getByRole("link", { name: "Yönetici girişi", exact: true }).click();
  await expect(page.locator(".case-table tbody tr")).toHaveCount(1);
  await page.getByRole("button", { name: "ÖRNEK-002 başvurusunu incele" }).click();
  await page.getByLabel("İç inceleme notu", { exact: true }).fill("YÖNETİCİYE ÖZEL not");
  await expect(page.getByRole("radio", { name: "Onayla", exact: true })).not.toBeChecked();
  await page.getByRole("button", { name: "AI değerlendirmesi oluştur", exact: true }).click();
  await expect(page.locator(".concern-level")).toHaveText("Düşük");
  expect(requests).toBe(1);
  await expect(page.getByRole("radio", { name: "Onayla", exact: true })).not.toBeChecked();
  await page.getByRole("radio", { name: "Onayla", exact: true }).check();
  await page.getByLabel(/Karar gerekçesi/).fill("Kurgusal açıklamalar incelendi.");
  await page.getByRole("button", { name: "Kararı gözden geçir" }).click();
  await expect(page.getByRole("region", { name: "Karar onayı" })).toContainText("Kurgusal açıklamalar incelendi.");
  await expect(page.locator(".case-overview .case-badge")).toHaveText("İnceleniyor");
  await page.getByRole("button", { name: "Simüle kararı onayla" }).click();
  await expect(page.getByText("Demo kararı kaydedildi", { exact: true })).toBeVisible();
  await expect(page.locator(".case-overview .case-badge")).toHaveText("Onaylandı");
  await context.grantPermissions(["clipboard-read", "clipboard-write"]);
  await page.getByRole("button", { name: "Raporu kopyala", exact: true }).click();
  const text = await page.evaluate(() => navigator.clipboard.readText());
  expect(text).toContain("YÖNETİCİYE ÖZEL"); expect(text).toContain("Başvuruya ilişkin ön inceleme riski: Düşük");
  expect(text).toContain("Karar: Onaylandı"); expect(text).toContain("Seyahat amacı açıklaması");
  await page.emulateMedia({ media: "print" });
  await expect(page.locator(".demo-header")).toBeHidden();
  await expect(page.locator("#submitted-answers")).toBeVisible();
  await expect(page.locator(".decision-saved")).toBeVisible();
  await page.emulateMedia({ media: "screen" });
  await page.screenshot({ path: testInfo.outputPath("admin-reviewed.png"), fullPage: true });
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: testInfo.outputPath("admin-detail-viewport.png") });
  await page.getByRole("button", { name: "Başvuru sahibine geç" }).click();
  await expect(page.locator(".receipt-card .case-badge")).toHaveText("Onaylandı");
  await expect(page.locator("#review-report, #human-review, #analysis-section")).toHaveCount(0);
  await expect(page.getByText("YÖNETİCİYE ÖZEL", { exact: false })).toHaveCount(0);
  expect(await page.evaluate(() => Object.keys(localStorage))).toEqual([]);
});

test("role switching preserves draft and submissions; repeated clicks do not duplicate cases", async ({ page }) => {
  await page.goto("/"); await loadSample(page); await next(page);
  await page.getByLabel("Mesleğiniz", { exact: true }).fill("Kurgusal mimar");
  await page.getByRole("link", { name: "Yönetici girişi", exact: true }).click();
  await expect(page.getByText("İlk başvuru için hazır", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Başvuru sahibine geç" }).click();
  await expect(page.getByLabel("Mesleğiniz", { exact: true })).toHaveValue("Kurgusal mimar");
  await next(page); await next(page);
  await page.getByLabel(/Yanıtlarımı kontrol ettim/).check();
  await page.getByRole("button", { name: "Başvuruyu gönder", exact: true }).evaluate((button: HTMLButtonElement) => { button.click(); button.click(); button.click(); });
  await expect(page.getByRole("heading", { name: "Başvurunuz alındı." })).toBeVisible();
  await openSubmitted(page);
  await expect(page.locator('[data-field-id="profile.occupation"] dd')).toHaveText("Kurgusal mimar");
  await page.getByRole("button", { name: "Başvurulara dön" }).click();
  await expect(page.locator(".case-table tbody tr")).toHaveCount(1);
  await page.getByRole("button", { name: "Başvuru sahibine geç" }).click();
  await page.getByRole("button", { name: "Yeni kurgusal başvuru" }).click();
  await loadSample(page); await finalStep(page); await submit(page);
  await page.getByRole("link", { name: "Yönetici girişi", exact: true }).click();
  await expect(page.locator(".case-table tbody tr")).toHaveCount(2);
});

test("admin seeding, reference search, status filters and decision editing", async ({ page }) => {
  await seedAdmin(page);
  await expect(page.locator(".case-table tbody tr")).toHaveCount(3);
  await expect(page.getByRole("button", { name: "Demo başvuruları yüklendi" })).toBeDisabled();
  await page.getByLabel("Başvuru referansı ara").fill("2026-002");
  await expect(page.locator(".case-table tbody tr")).toHaveCount(1);
  await page.getByRole("button", { name: "DEMO-2026-002 başvurusunu incele" }).click();
  await page.getByRole("radio", { name: "Reddet", exact: true }).check();
  await page.getByRole("button", { name: "Kararı gözden geçir" }).click();
  await expect(page.locator("#decision-error")).toBeVisible();
  await expect(page.locator("#decision-reason")).toBeFocused();
  await page.getByLabel(/Karar gerekçesi/).fill("Kurgusal açıklamalar tamamlanmadı.");
  await page.getByRole("button", { name: "Kararı gözden geçir" }).click();
  await page.getByRole("button", { name: "Simüle kararı onayla" }).click();
  await page.getByRole("button", { name: "Demo kararını düzenle" }).click();
  await expect(page.getByRole("radio", { name: "Reddet", exact: true })).not.toBeChecked();
  await page.getByRole("radio", { name: "Ek bilgi iste", exact: true }).check();
  await page.getByRole("button", { name: "Kararı gözden geçir" }).click();
  await expect(page.locator("#decision-error")).toBeVisible();
  await page.getByLabel(/Karar gerekçesi/).fill("Kalan geceler için konaklama planını açıklayın.");
  await page.getByRole("button", { name: "Kararı gözden geçir" }).click();
  await page.getByRole("button", { name: "Simüle kararı onayla" }).click();
  await page.getByRole("button", { name: "Başvurulara dön" }).click();
  await page.getByLabel("Duruma göre filtrele").selectOption("information_requested");
  await expect(page.locator(".case-table tbody tr")).toHaveCount(1);
  await page.getByLabel("Başvuru referansı ara").fill("does-not-exist");
  await expect(page.getByText("Eşleşen başvuru bulunamadı", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Filtreleri temizle" }).click();
  await expect(page.locator(".case-table tbody tr")).toHaveCount(3);
});
