import { test, expect } from "@playwright/test";
import { loadSample, finalStep, generate, editStep, next } from "./flow-helpers";

test("samples, report view, copy, print, freshness and clear", async ({ page, context }) => {
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/");
  await expect(page.locator("html")).toHaveAttribute("lang", "tr");
  await expect(page.locator("#review-report")).toHaveCount(0);
  for (const [sample, count] of [["clarification", 3], ["consistent", 0], ["missing", 4]] as const) {
    await loadSample(page, sample);
    await expect(page.locator("#review-report")).toHaveCount(0);
    await finalStep(page);
    await generate(page);
    await expect(page.locator("#report-title")).toBeFocused();
    await expect(page.locator(".form-column")).toBeHidden();
    await expect(page.locator(".finding-card")).toHaveCount(count);
  }
  await context.grantPermissions(["clipboard-read", "clipboard-write"]);
  await page.getByRole("button", { name: "Raporu kopyala" }).click();
  await expect(page.getByText("Rapor panoya kopyalandı.")).toBeVisible();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toContain("VizeLens — Ön inceleme raporu");
  await page.emulateMedia({ media: "print" });
  for (const selector of [".navigation-rail", ".form-column", ".report-actions", ".topbar"])
    await expect(page.locator(selector).first()).toBeHidden();
  await expect(page.locator("#review-report")).toBeVisible();
  await page.emulateMedia({ media: "screen" });
  await editStep(page, 4);
  await page.getByLabel("İnceleme notu").fill("Yeni açıklama");
  await expect(page.getByText(/Son rapor güncel değil/)).toBeVisible();
  await page.getByRole("button", { name: "Son raporu görüntüle" }).click();
  await expect(page.locator(".stale-alert")).toBeVisible();
  await expect(page.getByRole("button", { name: "Raporu kopyala" })).toBeDisabled();
  await expect(page.getByRole("button", { name: "Raporu yazdır" })).toBeDisabled();
  await page.emulateMedia({ media: "print" });
  await expect(page.locator(".finding-card").first()).toBeHidden();
  await page.emulateMedia({ media: "screen" });
  await editStep(page, 4);
  await generate(page);
  await expect(page.getByRole("button", { name: "Raporu kopyala" })).toBeEnabled();
  await editStep(page, 4);
  await page.getByRole("button", { name: "Temizle", exact: true }).click();
  await expect(page.getByLabel("Başvuru referansı")).toHaveValue("");
  await expect(page.locator("#review-report")).toHaveCount(0);
  expect(await page.evaluate(() => Object.keys(localStorage))).toEqual([]);
  expect(errors).toEqual([]);
});

test("step validation focuses errors and preserves values during back/edit navigation", async ({ page }) => {
  await page.goto("/");
  await next(page);
  await expect(page.getByText("Geçerli bir tarih girin.")).toHaveCount(2);
  await expect(page.locator('[aria-invalid="true"]')).toHaveCount(2);
  await expect(page.getByLabel("Gidiş tarihi")).toBeFocused();
  await expect(page.getByText("Bir tutar girin.")).toHaveCount(0);
  await loadSample(page, "dateConflict");
  await next(page);
  await expect(page.getByText("Dönüş tarihi gidiş tarihinden önce olamaz.")).toBeVisible();
  await expect(page.getByLabel("Dönüş tarihi")).toBeFocused();
  await loadSample(page);
  await page.getByLabel("Başvuru referansı").fill("KURGUSAL-42");
  await next(page);
  await page.getByRole("button", { name: "Geri", exact: true }).click();
  await expect(page.getByLabel("Başvuru referansı")).toHaveValue("KURGUSAL-42");
  await finalStep(page);
  await page.getByRole("button", { name: "Başvuru ve seyahat: Düzenle", exact: true }).click();
  await expect(page.getByLabel("Başvuru referansı")).toHaveValue("KURGUSAL-42");
  await editStep(page, 3);
  await page.getByLabel("Kullanılabilir seyahat bütçesi").fill("-100");
  await next(page);
  await expect(page.getByLabel("Kullanılabilir seyahat bütçesi")).toBeFocused();
  await expect(page.getByText(/0 veya daha büyük/)).toBeVisible();
  await page.getByLabel("Kullanılabilir seyahat bütçesi").fill("5000");
  const checkIn = await page.getByLabel("Giriş tarihi", { exact: true }).inputValue();
  await page.getByLabel("Çıkış tarihi", { exact: true }).fill(checkIn);
  await next(page);
  await expect(page.getByLabel("Çıkış tarihi", { exact: true })).toBeFocused();
  await page.getByRole("button", { name: "1. konaklamayı kaldır" }).click();
  await page.getByRole("button", { name: "Konaklama ekle" }).click();
  await expect(page.getByLabel("Giriş tarihi", { exact: true })).toHaveValue("");
  await page.getByRole("button", { name: "1. konaklamayı kaldır" }).click();
  await next(page);
  await generate(page);
  await page.reload();
  await expect(page.getByLabel("Gidiş tarihi")).toHaveValue("");
  await expect(page.locator("#review-report")).toHaveCount(0);
});
